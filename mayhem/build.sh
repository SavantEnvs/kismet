#!/usr/bin/env bash
#
# mayhem/build.sh — builds the four fuzz harnesses (+ standalone reproducers) and the project's own
# test programs. Kismet's full autotools build needs libnl/pcap/sqlite/protobuf etc. that the base lacks
# and pulls in the whole server, so the harnesses compile the self-contained parser sources directly.
set -euo pipefail

[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH

: "${SANITIZER_FLAGS=-fsanitize=address,undefined -fno-sanitize-recover=all -fno-omit-frame-pointer}"
: "${DEBUG_FLAGS:=-g -gdwarf-3}"
: "${CC:=clang}" ; : "${CXX:=clang++}" ; : "${LIB_FUZZING_ENGINE:=-fsanitize=fuzzer}"
: "${MAYHEM_JOBS:=$(nproc)}"
: "${COVERAGE_FLAGS=}"
: "${SRC:=/mayhem}"
: "${STANDALONE_FUZZ_MAIN:=/opt/mayhem/StandaloneFuzzTargetMain.c}"
export SANITIZER_FLAGS DEBUG_FLAGS CC CXX LIB_FUZZING_ENGINE MAYHEM_JOBS COVERAGE_FLAGS

cd "$SRC"

OUT="$SRC/mayhem/out"
mkdir -p "$OUT/fuzz" "$OUT/test"
INC="-I$SRC -I$SRC/mayhem/include -I$SRC/dot11_parsers"
CXXSTD="-std=c++20 -DKS_STR_ENCODING_NONE -w"

# compile_objs <objdir> <flags...> -- <sources...>: one object per source, MAYHEM_JOBS at a time
compile_objs() {
  local dir="$1"; shift
  local flags=()
  while [ "$1" != "--" ]; do flags+=("$1"); shift; done; shift
  mkdir -p "$dir"
  local pids=() s o rc=0
  for s in "$@"; do
    o="$dir/${s//\//_}.o"
    while [ "$(jobs -rp | wc -l)" -ge "$MAYHEM_JOBS" ]; do wait -n || rc=1; done
    "$CXX" -c "${flags[@]}" "$s" -o "$o" &
  done
  while [ "$(jobs -rp | wc -l)" -gt 0 ]; do wait -n || rc=1; done
  [ "$rc" -eq 0 ] || { echo "compile failed in $dir" >&2; return 1; }
}

SAN="$SANITIZER_FLAGS $DEBUG_FLAGS"
COV="-fsanitize=fuzzer-no-link"

DOT11_SRCS=(dot11_parsers/*.cc kaitaistream.cc)
BTLE_SRCS=(bluetooth_parsers/bt_assigned.cc bluetooth_parsers/btle_adtypes.cc bluetooth_parsers/btle_battery.cc
           bluetooth_parsers/btle_beacon.cc bluetooth_parsers/btle_continuity.cc bluetooth_parsers/btle_ranging.cc
           bluetooth_parsers/btle_sensor.cc bluetooth_parsers/btle_tracker.cc bluetooth_parsers/btle_vendor.cc)
UAV_SRCS=(uav_parsers/opendroneid.cc)
CELL_SRCS=(phy_cell_decisions.cc censor.cc diagspec/enrichment/cpp/lte_band.cpp)

# 1) Sanitized project sources, one object directory per harness
compile_objs "$OUT/fuzz/dot11" $CXXSTD $INC $SAN $COV -O1 -- "${DOT11_SRCS[@]}"
compile_objs "$OUT/fuzz/btle"  $CXXSTD $INC $SAN $COV -O1 -- "${BTLE_SRCS[@]}"
compile_objs "$OUT/fuzz/uav"   $CXXSTD $INC $SAN $COV -O1 -- "${UAV_SRCS[@]}"
compile_objs "$OUT/fuzz/cell"  $CXXSTD $INC $SAN $COV -O1 -- "${CELL_SRCS[@]}"

# 2) LSan off hook + the standalone driver (compiled as C so its LLVMFuzzerTestOneInput ref keeps C linkage)
$CXX $SAN -c mayhem/lsan_off.cc -o "$OUT/lsan_off.o"
$CC $SAN -c "$STANDALONE_FUZZ_MAIN" -o "$OUT/standalone_main.o"

# 3) Harnesses: fuzzer + standalone, each
link_harness() {
  local name="$1" dir="$2"
  $CXX $CXXSTD $INC $SAN $COV -O1 -c "mayhem/harnesses/$name.cc" -o "$OUT/$name.o"
  $CXX $SAN $COV $LIB_FUZZING_ENGINE "$OUT/$name.o" "$OUT/fuzz/$dir"/*.o "$OUT/lsan_off.o" -lcrypto -o "$SRC/$name"
  $CXX $SAN $COV "$OUT/$name.o" "$OUT/standalone_main.o" "$OUT/fuzz/$dir"/*.o "$OUT/lsan_off.o" -lcrypto -o "$SRC/$name-standalone"
}
link_harness fuzz_dot11_ie dot11
link_harness fuzz_btle_decoders btle
link_harness fuzz_opendroneid uav
link_harness fuzz_cell_decisions cell

# 4) Upstream's own test programs, normal flags (no sanitizers), run by mayhem/test.sh
TFLAGS="-O1 -w $COVERAGE_FLAGS"
$CXX -std=c++17 $TFLAGS $INC test/btle_tracker/decoder_test.cc bluetooth_parsers/btle_tracker.cc \
  -o "$OUT/test/btle_tracker_test"
$CXX -std=c++20 $TFLAGS -DKS_STR_ENCODING_NONE $INC test/cell_decisions/decisions_test.cc \
  phy_cell_decisions.cc censor.cc diagspec/enrichment/cpp/lte_band.cpp -o "$OUT/test/cell_decisions_test"
# freq_to_chan_test includes "../config.h" (generated by upstream's configure); stage a copy of the
# few files it needs next to our config.h instead of writing into the source tree.
STAGE="$OUT/test/freq_stage"
rm -rf "$STAGE"; mkdir -p "$STAGE/test/linuxwifi_channels" "$STAGE/capture_linux_wifi"
cp mayhem/include/config.h "$STAGE/config.h"
cp test/linuxwifi_channels/freq_to_chan_test.c "$STAGE/test/linuxwifi_channels/"
cp capture_linux_wifi/linux_netlink_control.[ch] capture_linux_wifi/nl80211.h "$STAGE/capture_linux_wifi/"
cp wifi_ht_channels.[ch] "$STAGE/"
(cd "$STAGE" && $CC $TFLAGS -I. test/linuxwifi_channels/freq_to_chan_test.c wifi_ht_channels.c \
  capture_linux_wifi/linux_netlink_control.c -o "$OUT/test/freq_to_chan_test")
